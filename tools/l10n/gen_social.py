# Writes app/lib/core/social_text.dart from social_texts.py (docs K93).
#   python3 tools/l10n/gen_social.py
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from social_texts import TOPICS
lines = []
for t, vs in TOPICS.items():
    for i, (en, _) in enumerate(vs):
        key = 'sm' + t[0].upper() + t[1:] + str(i)
        ps = sorted(set(re.findall(r'\{(\w+)\}', en)))
        call = f"l.{key}({', '.join(ps)})" if ps else f"l.{key}"
        lines.append(f"      (FanTopic.{t}, {i}) => {call},")
counts = {t: len(vs) for t, vs in TOPICS.items() if len(vs) != 3}
count_lines = '\n'.join(f'      FanTopic.{t} => {n},' for t, n in counts.items())
dart = '''// Generated by tools/l10n/gen_social.py from social_texts.py (docs K93).
import 'package:game/game.dart';

import '../l10n/gen/app_localizations.dart';

/// The words of a social feed item ([title]: its song or album, [name]:
/// the player, [n]: its number, formatted, [rival]: a beef's rival).
String socialText(AppLocalizations l, FanTopic topic, int variant,
        {required String title,
        required String name,
        required String n,
        String rival = ''}) =>
    switch ((topic, variant % socialVariants(topic))) {
''' + '\n'.join(lines) + '''
      _ => '',
    };

/// Wordings of [topic]: 3, more for comments and replies (docs K238).
int socialVariants(FanTopic topic) => switch (topic) {
''' + count_lines + '''
      _ => 3,
    };
'''
open(os.path.join(here, '..', '..', 'app', 'lib', 'core', 'social_text.dart'), 'w').write(dart)
